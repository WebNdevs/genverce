export async function seed30Influencers(client = prisma) {
  console.log('🚀 Starting creation of 30 AI Influencers on Genverce...\n');

  // Find demo customer for reviews
  let customer = await client.user.findFirst({
    where: { role: 'CUSTOMER' },
    orderBy: { createdAt: 'asc' },
  });

  if (!customer) {
    console.log('Creating demo customer for reviews...');
    customer = await client.user.create({
      data: {
        email: 'customer@genverce.ai',
        name: 'Enterprise Client',
        password: '$2b$12$eXampleHashedPasswordPlaceholderForSeed12345',
        role: 'CUSTOMER',
      },
    });
  }

  for (let idx = 0; idx < NEW_INFLUENCERS.length; idx++) {
    const data = NEW_INFLUENCERS[idx];
    console.log(`[${idx + 1}/30] Creating/Updating: ${data.name} (${data.category})...`);

    const existing = await client.influencer.findFirst({
      where: { name: data.name },
    });

    const influencerPayload = {
      name: data.name,
      bio: data.bio,
      avatar: data.avatar,
      industries: data.industries,
      contentStyle: data.contentStyle,
      languages: data.languages,
      rating: data.rating,
      totalProjects: data.totalProjects,
      totalReviews: data.totalReviews,
      isActive: true,
      hourlyRate: data.hourlyRate,
      serviceType: data.serviceType,
      voiceId: data.voiceId,
      systemPrompt: data.systemPrompt,
      topic: data.topic,
      outOfTopicMessage: data.outOfTopicMessage,
      locationCity: data.locationCity,
      locationState: data.locationState,
      locationCountry: data.locationCountry,
      locationAddress: data.locationAddress,
      locationPincode: data.locationPincode,
      deletedAt: null,
    };

    const influencer = existing
      ? await client.influencer.update({
          where: { id: existing.id },
          data: influencerPayload,
        })
      : await client.influencer.create({
          data: influencerPayload,
        });

    // 1. Upsert Packages
    for (const pkg of STANDARD_PACKAGES) {
      const existingPkg = await client.influencerPackage.findFirst({
        where: { influencerId: influencer.id, type: pkg.type },
      });
      if (existingPkg) {
        await client.influencerPackage.update({
          where: { id: existingPkg.id },
          data: {
            name: pkg.name,
            price: pkg.price,
            videoCount: pkg.videoCount,
            description: pkg.description,
            isMonthly: pkg.isMonthly,
            isActive: true,
            sortOrder: pkg.sortOrder,
          },
        });
      } else {
        await client.influencerPackage.create({
          data: {
            influencerId: influencer.id,
            type: pkg.type,
            name: pkg.name,
            price: pkg.price,
            videoCount: pkg.videoCount,
            description: pkg.description,
            isMonthly: pkg.isMonthly,
            isActive: true,
            sortOrder: pkg.sortOrder,
          },
        });
      }
    }

    // 2. Upsert Portfolio Items
    const existingPortfolioCount = await client.influencerPortfolio.count({
      where: { influencerId: influencer.id },
    });
    if (existingPortfolioCount === 0) {
      const slug = data.avatar.split('/').pop()?.replace('.jpg', '') || 'item';
      for (const item of data.portfolio) {
        await client.influencerPortfolio.create({
          data: {
            influencerId: influencer.id,
            videoUrl: `/videos/sample-${slug}.mp4`,
            thumbnailUrl: `/images/thumbnails/${slug}-thumb.jpg`,
            title: `${influencer.name} - ${item.title}`,
            description: item.description,
          },
        });
      }
    }

    // 3. Upsert AIConfig
    const existingAIConfig = await client.aIConfig.findUnique({
      where: { influencerId: influencer.id },
    });
    if (!existingAIConfig) {
      await client.aIConfig.create({
        data: {
          influencerId: influencer.id,
          chatModel: 'gpt-4o',
          postModel: 'gpt-4o',
        },
      });
    }

    // 4. Create sample Orders & Reviews if none exist
    const existingReviewsCount = await client.review.count({
      where: { influencerId: influencer.id },
    });

    if (existingReviewsCount === 0 && customer && data.reviews && data.reviews.length > 0) {
      for (let rIdx = 0; rIdx < data.reviews.length; rIdx++) {
        const rev = data.reviews[rIdx];
        const daysAgo = 10 + rIdx * 12;
        const pastDate = new Date();
        pastDate.setDate(pastDate.getDate() - daysAgo);

        const order = await client.order.create({
          data: {
            customerId: customer.id,
            influencerId: influencer.id,
            projectBrief: JSON.stringify({
              productName: `${data.category} Campaign`,
              tagline: `Accelerate engagement with ${influencer.name}`,
              keyPoints: ['High authority', 'Viral reach', 'Defensible metrics'],
              tone: data.contentStyle,
            }),
            package: PackageType.PACK_5,
            deliveryType: DeliveryType.QUALITY_CHECKED,
            status: OrderStatus.DELIVERED,
            price: 39.99,
            videosOrdered: 5,
            videosDelivered: 5,
            aiDisclosure: true,
            createdAt: pastDate,
            deliveredAt: pastDate,
          },
        });

        await client.review.create({
          data: {
            orderId: order.id,
            customerId: customer.id,
            influencerId: influencer.id,
            rating: rev.rating,
            comment: rev.comment,
            createdAt: pastDate,
          },
        });
      }
    }

    console.log(`   ✓ ${data.name} ready (ID: ${influencer.id})`);
  }

  // Count active influencers
  const activeCount = await client.influencer.count({
    where: { deletedAt: null },
  });

  console.log(`\n========================================`);
  console.log(`🎉 All 30 AI Influencers successfully created/synced!`);
  console.log(`📊 Total active influencers in platform: ${activeCount}`);
  console.log(`========================================\n`);
}

if (require.main === module) {
  seed30Influencers()
    .catch((e) => {
      console.error('❌ Seeding failed:', e);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
